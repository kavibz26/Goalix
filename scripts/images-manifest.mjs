// Generates IMAGES.md — a checklist of every image path the catalog references.
// Run after updating src/data/products.json. Output stays out of public/ so it
// is never served.
//
//   npm run images:manifest

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const productsPath = resolve(root, "src/data/products.json");
const outPath = resolve(root, "IMAGES.md");

const data = JSON.parse(readFileSync(productsPath, "utf8"));
const teams = Array.isArray(data.teams) ? data.teams : [];

const paths = new Set(["/images/hero.jpg"]);
for (const team of teams) {
  for (const kit of team.kits ?? []) {
    if (kit.images?.front) paths.add(kit.images.front);
    if (kit.images?.back) paths.add(kit.images.back);
  }
}

const list = [...paths].sort();
const publicDir = resolve(root, "public");

const rows = list
  .map((p) => {
    const onDisk = existsSync(resolve(publicDir, "." + p));
    return `- [${onDisk ? "x" : " "}] \`${p}\``;
  })
  .join("\n");

const md = `# Images checklist

Auto-generated by \`scripts/images-manifest.mjs\` from \`src/data/products.json\`.
A missing file renders a "תמונה בקרוב" state on the site — never a placeholder image.

${teams.length === 0 ? "> products.json has no teams yet.\n" : ""}
Total referenced files: **${list.length}**

${rows}
`;

writeFileSync(outPath, md);
console.log(`Wrote ${outPath} (${list.length} paths, ${teams.length} teams).`);
